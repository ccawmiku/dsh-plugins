import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { mkdir, mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { spawn } from 'node:child_process';
import { once } from 'node:events';

await mkdir('test-results', { recursive: true });
const dataDir = await mkdtemp(join(tmpdir(), 'salon-ui-'));
const child = spawn(process.execPath, ['scripts/dev.mjs', '--demo'], { env: { ...process.env, SALON_PORT: '0', SALON_DATA_DIR: dataDir }, windowsHide: true, stdio: ['ignore', 'pipe', 'pipe'] });
const url = await new Promise((resolve, reject) => {
  const timer = setTimeout(() => reject(new Error('演示服务启动超时')), 15000);
  child.once('error', error => { clearTimeout(timer); reject(error); });
  child.stdout.on('data', bytes => { const match = bytes.toString().match(/http:\/\/127\.0\.0\.1:\d+/); if (match) { clearTimeout(timer); resolve(match[0]); } });
  child.stderr.on('data', bytes => { clearTimeout(timer); reject(new Error(bytes.toString())); });
});
const browser = await chromium.launch({ headless: true });
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 980 } });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(url);
  await page.getByRole('heading', { name: '沙龙客厅', exact: true }).waitFor();
  assert.ok(await page.getByText('演示模式 · 回复为测试样例，不连接真实模型').isVisible());
  await page.screenshot({ path: 'test-results/desktop.png', fullPage: true });
  await page.getByRole('navigation').getByRole('button').filter({ hasText: '小春' }).click();
  await page.getByRole('heading', { name: '与小春的私语' }).waitFor();
  await page.getByRole('textbox', { name: '聊天消息' }).fill('只在私聊出现的UI验收暗号');
  await page.getByRole('button', { name: '发送 ↗' }).click();
  await page.getByText('主人，茶已经准备好了。', { exact: false }).waitFor();
  await page.getByRole('button', { name: '停止', exact: true }).waitFor({ state: 'hidden' });
  await page.screenshot({ path: 'test-results/private-chat.png', fullPage: true });
  await page.getByRole('navigation').getByRole('button').filter({ hasText: '沙龙客厅' }).click();
  await page.getByRole('heading', { name: '沙龙客厅', exact: true }).waitFor();
  await page.waitForTimeout(1000);
  assert.equal(await page.getByText('只在私聊出现的UI验收暗号', { exact: true }).count(), 0);
  const composer = page.getByRole('textbox', { name: '聊天消息' });
  await composer.fill('@');
  await page.getByRole('listbox', { name: '点名成员' }).waitFor();
  assert.equal(await page.getByRole('option').count(), 5);
  await page.screenshot({ path: 'test-results/mention-menu.png', fullPage: true });
  await page.getByRole('option').filter({ hasText: '@真白' }).click();
  assert.equal(await composer.inputValue(), '@真白 ');
  await composer.fill('@夕');
  assert.equal(await page.getByRole('option').count(), 1);
  await composer.press('Enter');
  assert.equal(await composer.inputValue(), '@夕雾 ');
  assert.equal(await page.getByRole('listbox').count(), 0);
  await composer.fill('@真白 你想聊什么？');
  await page.getByRole('button', { name: '发送 ↗' }).click();
  await page.getByText('……门都开了，就进来坐吧。', { exact: false }).waitFor();
  await page.getByRole('button', { name: '停止', exact: true }).waitFor({ state: 'hidden' });
  const sent = await page.evaluate(async () => (await (await fetch('/api/salon/state?room=group')).json()).room.messages);
  assert.equal(sent.filter(m => m.speaker !== 'user' && m.speaker !== 'system').length, 1);
  assert.equal(sent.find(m => m.speaker !== 'user').speaker, 'mashiro');
  await page.getByRole('navigation').getByRole('button').filter({ hasText: '沙龙设置' }).click();
  const settings = page.getByRole('dialog');
  assert.equal(await settings.getByLabel('目标上下文（tokens）').inputValue(), '500000');
  await settings.getByLabel('默认视频方式').selectOption('native');
  await settings.getByRole('button', { name: '保存设置' }).click();
  await page.getByRole('dialog').waitFor({ state: 'hidden' });
  await page.getByRole('navigation').getByRole('button').filter({ hasText: '沙龙设置' }).click();
  assert.equal(await page.getByRole('dialog').getByLabel('默认视频方式').inputValue(), 'native');
  await page.getByRole('dialog').getByRole('button', { name: '关闭', exact: true }).click();
  await page.getByRole('button', { name: '角色设定', exact: true }).first().click();
  assert.ok((await page.getByRole('dialog').getByLabel('完整人设').inputValue()).includes('女仆'));
  await page.getByRole('dialog').getByRole('button', { name: '关闭', exact: true }).click();
  await page.getByRole('navigation').getByRole('button').filter({ hasText: '记忆与日记' }).click();
  await page.getByRole('button', { name: '＋ 添加记忆 / 世界设定' }).click();
  await page.getByLabel('记忆正文').fill('我们约好一起看电影。');
  await page.getByLabel('唤起关键词（逗号分隔）').fill('电影，周末');
  await page.getByRole('button', { name: '保存这条记忆' }).click();
  await page.getByText('我们约好一起看电影。', { exact: true }).waitFor();
  await page.screenshot({ path: 'test-results/memories.png', fullPage: true });
  await page.getByRole('dialog').getByRole('button', { name: '关闭', exact: true }).click();
  await page.setViewportSize({ width: 480, height: 900 });
  await page.screenshot({ path: 'test-results/mobile.png', fullPage: true });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth));
  assert.deepEqual(errors, []);
  console.log('界面验收通过：@名单、点击/键盘插入、点名路由、群聊/私聊隔离、500k设置、视频模式保存、角色与记忆编辑、窄屏布局，无浏览器脚本错误。');
} finally {
  await browser.close();
  const ended = once(child, 'exit'); child.kill(); await ended;
  await rm(dataDir, { recursive: true, force: true, maxRetries: 5, retryDelay: 100 });
}
